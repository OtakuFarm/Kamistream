-- ============================================================================
-- CATALOGUE HERO BANNERS — homepage hero banner management from admin panel
-- ============================================================================

create table if not exists public.hero_banners (
  id          bigint generated by default as identity primary key,
  title       text not null,
  subtitle    text,
  image_url   text not null,
  link_url    text,
  link_text   text,
  is_active   boolean not null default true,
  sort_order  integer not null default 0,
  start_date  date,
  end_date    date,
  created_at  timestamptz not null default now()
);
create index if not exists hero_banners_active_idx
  on public.hero_banners (is_active, sort_order);

-- RLS: public can read active banners; admin can manage
alter table public.hero_banners enable row level security;
drop policy if exists "Anyone can read active hero banners" on public.hero_banners;
create policy "Anyone can read active hero banners"
  on public.hero_banners for select
  using (is_active = true);
drop policy if exists "Admin can manage hero banners" on public.hero_banners;
create policy "Admin can manage hero banners"
  on public.hero_banners for all
  using (auth.uid() is not null);