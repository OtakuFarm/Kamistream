-- ============================================================================
-- CATALOGUE EMBED SOURCES — per-episode video hosts for catalogue titles
-- ============================================================================

create table if not exists public.catalogue_embed_sources (
  id              bigint generated by default as identity primary key,
  episode_id      bigint not null references public.catalogue_episodes(id) on delete cascade,
  source_name     text not null,        -- e.g. MP4Upload, StreamSB, YouTube
  embed_url       text not null,
  quality         text default '720p',
  language        text default 'sub',
  is_active       boolean not null default true,
  sort_order      integer not null default 0,
  created_at      timestamptz not null default now()
);
create index if not exists catalogue_embed_sources_ep_idx
  on public.catalogue_embed_sources (episode_id, is_active);

-- RLS: public can read active sources; admin (service role / authed) can manage
alter table public.catalogue_embed_sources enable row level security;
drop policy if exists "Anyone can read active embed sources" on public.catalogue_embed_sources;
create policy "Anyone can read active embed sources"
  on public.catalogue_embed_sources for select
  using (is_active = true);
drop policy if exists "Admin can manage embed sources" on public.catalogue_embed_sources;
create policy "Admin can manage embed sources"
  on public.catalogue_embed_sources for all
  using (auth.uid() is not null);